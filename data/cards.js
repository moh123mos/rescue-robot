/* تنسيق الأرقام والتعابير للعرض (DOM فقط) */
window.Num = {
  eastern: true,
  map: "٠١٢٣٤٥٦٧٨٩",
  digits(s) {
    return this.eastern ? String(s).replace(/[0-9]/g, d => this.map[+d]) : String(s).replace(/[٠-٩]/g, d => "٠١٢٣٤٥٦٧٨٩".indexOf(d));
  },
  /* يحوّل {{expr}} إلى span LTR ثم يطبّق نظام الأرقام */
  fmt(s) {
    const html = String(s).replace(/\{\{(.+?)\}\}/g, '<span class="expr" dir="ltr">$1</span>');
    return this.digits(html);
  }
};
